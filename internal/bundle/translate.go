package bundle

import (
	"fmt"
	"path"
	"strconv"
	"strings"
)

// ScriptsDirName is the folder, inside the copy of a bundle's files, that
// holds the scripts notebooks are translated to (ADR-031 section 5).
const ScriptsDirName = "_clavesa_notebooks"

// ScriptPath is where the translated script of a notebook goes, relative
// to the bundle root.
func ScriptPath(notebookRel string) string {
	return path.Join(ScriptsDirName, strings.TrimSuffix(notebookRel, path.Ext(notebookRel))+".py")
}

// TranslateNotebook turns a notebook into one Python script the runner
// runs (ADR-031 section 5): Python cells as they are, SQL cells as
// statements through the runner's notebook SQL (widget values bound as
// :name, ${name} and {{name}} replaced as text), %run notebooks inlined,
// %fs as dbutils.fs calls, %md dropped. What the plan refuses (%pip, %sh,
// other languages) is an error here too, so a run never meets it.
func TranslateNotebook(root, rel string) (string, error) {
	var sb strings.Builder
	fmt.Fprintf(&sb, "# Generated by clavesa from %s (ADR-031). Do not edit: the notebook is the source.\n", rel)
	sb.WriteString("import bundle_task as __clavesa_bt\n")
	if err := translateInto(&sb, root, rel, map[string]bool{}); err != nil {
		return "", err
	}
	return sb.String(), nil
}

func translateInto(sb *strings.Builder, root, rel string, stack map[string]bool) error {
	if stack[rel] {
		return fmt.Errorf("%s: %%run cycle", rel)
	}
	stack[rel] = true
	defer delete(stack, rel)
	nb, err := ParseNotebook(root, rel)
	if err != nil {
		return err
	}
	if nb.Language != "python" && nb.Language != "sql" {
		return fmt.Errorf("%s: %s notebooks are not supported: clavesa runs Python and SQL", rel, nb.Language)
	}
	for _, c := range nb.Cells {
		line := c.Line
		if c.MagicLine > 0 {
			line = c.MagicLine
		}
		fmt.Fprintf(sb, "\n# --- %s:%d (%s) ---\n", rel, line, cellKind(c))
		switch c.Lang {
		case "md":
			continue
		case "python":
			sb.WriteString(c.Body)
			sb.WriteString("\n")
		case "sql":
			fmt.Fprintf(sb, "__clavesa_bt.notebook_sql(spark, __clavesa_names__, dbutils, %s, %s)\n", pyStr(c.Body), pyStr(fmt.Sprintf("%s:%d", rel, c.Line)))
		case "magic":
			switch c.Magic {
			case "run":
				target, err := RunTarget(root, rel, c.Args)
				if err != nil {
					return fmt.Errorf("%s:%d: %w", rel, line, err)
				}
				fmt.Fprintf(sb, "# %%run %s: inlined from %s\n", c.Args, target)
				if err := translateInto(sb, root, target, stack); err != nil {
					return err
				}
				fmt.Fprintf(sb, "\n# --- end of %%run %s ---\n", c.Args)
			case "fs":
				fmt.Fprintf(sb, "__clavesa_bt.notebook_fs(dbutils, %s)\n", pyStr(c.Args))
			default:
				return fmt.Errorf("%s:%d: %%%s runs only in Databricks", rel, line, c.Magic)
			}
		default:
			return fmt.Errorf("%s:%d: %%%s: clavesa runs Python and SQL cells only", rel, line, c.Magic)
		}
	}
	return nil
}

func cellKind(c Cell) string {
	if c.Magic != "" {
		return "%" + c.Magic
	}
	return c.Lang
}

// pyStr is a Python string literal for s.
func pyStr(s string) string {
	return strconv.Quote(s)
}
